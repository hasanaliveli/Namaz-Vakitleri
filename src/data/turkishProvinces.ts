export function getProvinceByPlaka(plaka: number): Province {
  return TURKISH_PROVINCES.find((p) => p.plaka === plaka) ?? TURKISH_PROVINCES[33]; // İstanbul fallback
}

export function normalizeTurkishText(text: string): string {
  return text
    .toLocaleLowerCase('tr-TR')
    .replace(/ğ/g, 'g')
    .replace(/ü/g, 'u')
    .replace(/ş/g, 's')
    .replace(/ı/g, 'i')
    .replace(/i̇/g, 'i')
    .replace(/ö/g, 'o')
    .replace(/ç/g, 'c')
    .trim();
}

export function formatPlaka(plaka: number): string {
  return plaka < 10 ? `0${plaka}` : `${plaka}`;
}

export function haversineDistanceKm(lat1: number, lng1: number, lat2: number, lng2: number): number {
  const toRad = (deg: number) => (deg * Math.PI) / 180;
  const R = 6371;
  const dLat = toRad(lat2 - lat1);
  const dLng = toRad(lng2 - lng1);
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos(toRad(lat1)) * Math.cos(toRad(lat2)) * Math.sin(dLng / 2) * Math.sin(dLng / 2);
  return R * 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
}

export function findNearestProvince(lat: number, lng: number): {province: Province; distanceKm: number} {
  let nearest = TURKISH_PROVINCES[33];
  let minDistance = Infinity;

  for (const province of TURKISH_PROVINCES) {
    const d = haversineDistanceKm(lat, lng, province.lat, province.lng);
    if (d < minDistance) {
      minDistance = d;
      nearest = province;
    }
  }

  return {
    province: nearest,
    distanceKm: Math.round(minDistance * 10) / 10,
  };
}
